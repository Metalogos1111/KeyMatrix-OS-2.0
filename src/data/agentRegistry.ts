export const ALLOWED_TASK_TRANSITIONS: Record<TaskStatus, TaskStatus[]> = {
  DRAFT: ['PLANNED', 'CANCELLED'],
  PLANNED: ['AWAITING_AUTHORIZATION', 'RUNNING', 'CANCELLED'],
  AWAITING_AUTHORIZATION: ['RUNNING', 'CANCELLED', 'FAILED'],
  RUNNING: ['WAITING_FOR_TOOL', 'WAITING_FOR_CORE', 'VERIFYING', 'COMPLETED', 'FAILED', 'CANCELLED'],
  WAITING_FOR_TOOL: ['RUNNING', 'FAILED', 'CANCELLED'],
  WAITING_FOR_CORE: ['RUNNING', 'FAILED', 'CANCELLED'],
  VERIFYING: ['COMPLETED', 'FAILED', 'CANCELLED'],
  COMPLETED: [],
  FAILED: ['PLANNED'],
  CANCELLED: ['PLANNED'],
};

export function canTransitionTask(from: TaskStatus, to: TaskStatus): boolean {
  return ALLOWED_TASK_TRANSITIONS[from]?.includes(to) ?? false;
}
